const {chromium} = require('playwright');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const previewDir = process.env.BUTLER_PREVIEW_DIR || path.join(require('os').tmpdir(), 'butler-layout-previews');
fs.mkdirSync(previewDir, {recursive:true});
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1500,height:1100}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.setContent('<html><body style="margin:0"></body></html>');
 await page.addScriptTag({content:fs.readFileSync(path.join(root,'custom_components/biofects_butler/frontend/biofects-butler-panel.js'),'utf8')});
 await page.evaluate(() => {
  const panel=document.createElement('biofects-butler-panel');
  panel._hass={states:{'light.kitchen':{entity_id:'light.kitchen',state:'off',attributes:{friendly_name:'Kitchen lights'}},'switch.coffee':{entity_id:'switch.coffee',state:'on',attributes:{friendly_name:'Coffee machine'}}},panels:{},callService(){throw new Error('Designer must not operate entities')}};
  panel._load=async()=>{};
  const sections=[['entity_controls','Living room'],['entity_controls','Kitchen']].map(([type,title],i)=>({section_id:`panel_${i}`,slot:`panel_${i}`,type,title,bindings:[],actions:[],column_span:2,row_span:1}));
  panel._draft={schema_version:1,profile_id:'demo',name:'Whole home',default_screen_id:'home',screens:[{screen_id:'home',title:'Home',composition:'freeform_grid',sections}]};
  panel._snapshot={profiles:[panel._draft],displays:[]};
  panel._selectedId='demo';panel._activeScreenId='home';panel._activeWorkspace='screens';panel._activeSectionSlot='panel_0';
  document.body.appendChild(panel);
 });
 const snapshot=()=>page.evaluate(()=>document.querySelector('biofects-butler-panel')._draft);
 await page.locator('.visual-library').waitFor();
 await page.locator('[data-library-search]').fill('kitchen');
 assert.equal(await page.locator('[data-library-entity]').count(),1);
 await page.locator('[data-library-entity="light.kitchen"]').click();
 assert.equal((await snapshot()).screens[0].sections[0].bindings[0].target_id,'light.kitchen');
 await page.locator('.visual-inspector [data-binding-tap-mode]').selectOption('toggle');
 assert.equal((await snapshot()).screens[0].sections[0].actions[0].type,'toggle');
 await page.locator('.visual-inspector [data-binding-name]').fill('Main lights');
 await page.locator('.visual-inspector [data-binding-name]').press('Tab');
 await page.locator('[data-move-canvas-card]').selectOption('1');
 assert.equal((await snapshot()).screens[0].sections[1].bindings[0].name,'Main lights');
 assert.equal((await snapshot()).screens[0].sections[1].actions[0].type,'toggle');
 await page.locator('[data-library-search]').fill('coffee');
 await page.locator('[data-library-entity="switch.coffee"]').dragTo(page.locator('.canvas-panel').first());
 assert.equal((await snapshot()).screens[0].sections[0].bindings[0].target_id,'switch.coffee');
 await page.locator('.canvas-panel').nth(1).locator('[data-binding-card]').dragTo(page.locator('.canvas-panel').first());
 assert.equal((await snapshot()).screens[0].sections[1].bindings.length,0);
 assert.equal((await snapshot()).screens[0].sections[0].bindings.length,2);
 await page.locator('.canvas-panel').first().locator('[data-binding-card]').first().scrollIntoViewIfNeeded();
 await page.locator('.advanced-canvas').scrollIntoViewIfNeeded();
 const from = await page.locator('.canvas-panel').first().locator('[data-binding-card]').first().boundingBox();
 const to = await page.locator('.canvas-cell[data-grid-column="1"][data-grid-row="4"]').boundingBox();
 await page.mouse.move(from.x+10,from.y+10);await page.mouse.down();await page.mouse.move(from.x+20,from.y+20,{steps:3});await page.mouse.move(to.x+10,to.y+10,{steps:10});await page.mouse.up();
 assert.equal((await snapshot()).screens[0].sections.length,3);
 assert.equal((await snapshot()).screens[0].sections[2].bindings.length,1);
 await page.locator('[data-action="duplicate-canvas-panel"]').first().click();
 assert.equal((await snapshot()).screens[0].sections.length,4);
 await page.locator('[data-action="sections-flow"]').click();
 assert.ok((await snapshot()).screens[0].sections.every(s=>s.column_span===6&&!s.grid_row&&!s.grid_column));
 await page.locator('.canvas-panel').first().locator('[data-binding-card]').click();
 await page.locator('.visual-inspector [data-binding-tap-mode]').selectOption('more_info');
 await page.locator('.visual-inspector [data-binding-display-mode]').selectOption('row');
 await page.locator('[data-library-search]').fill('');
 await page.locator('.visual-workspace').screenshot({path:path.join(previewDir,'visual-sections-designer.png')});
 fs.writeFileSync(path.join(previewDir,'visual-designer-profile.json'),JSON.stringify(await snapshot(),null,2));
 await page.locator('[data-library-panel="heading"]').click();
 await page.locator('[data-design-title]').fill('Our home');await page.locator('[data-design-title]').press('Tab');
 await page.locator('[data-design-text]').fill('Welcome home');await page.locator('[data-design-text]').press('Tab');
 assert.ok((await page.locator('.visual-design-preview').allTextContents()).includes('Welcome home'));
 await page.evaluate(()=>{const el=document.querySelector('biofects-butler-panel');el._hass.states['input_text.greeting']={entity_id:'input_text.greeting',state:'Good evening, family',attributes:{friendly_name:'Home greeting'}};});
 await page.locator('[data-library-search]').fill('greeting');
 await page.locator('[data-library-entity="input_text.greeting"]').click();
 assert.ok((await page.locator('.visual-design-preview').allTextContents()).includes('Good evening, family'));
 await page.locator('.canvas-options > summary').click();
 await page.locator('[data-show-page-header]').uncheck();
 assert.equal((await snapshot()).screens[0].show_header,false);
 await page.locator('[data-field="title"]').fill('Family command center');await page.locator('[data-field="title"]').press('Tab');
 assert.equal((await snapshot()).screens[0].title,'Family command center');
 fs.writeFileSync(path.join(previewDir,'visual-designer-profile.json'),JSON.stringify(await snapshot(),null,2));
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 assert.deepEqual(errors,[]);
 console.log('Visual designer browser test passed: search, entity drag/drop, card moves, actions, inspector, duplicates, sections flow, mobile overflow.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
