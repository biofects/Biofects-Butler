const {chromium} = require('playwright');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const previewDir = process.env.BUTLER_PREVIEW_DIR || path.join(require('os').tmpdir(), 'butler-layout-previews');
fs.mkdirSync(previewDir, {recursive:true});
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1500,height:1100}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.setContent('<html><body style="margin:0"></body></html>');
 await page.addScriptTag({content:fs.readFileSync(path.join(root,'custom_components/biofects_butler/frontend/biofects-butler-panel.js'),'utf8')});
 await page.evaluate(() => {
  const panel=document.createElement('biofects-butler-panel');
  panel._hass={states:{},panels:{}};
  panel._load=async()=>{};
  const sections=[['assistant','Home assistant'],['status_overview','Home at a glance'],['weather','Weather & forecast'],['media','Now playing'],['events','Today’s agenda'],['quick_commands','Favorite scenes']].map(([type,title],i)=>({section_id:`panel_${i}`,slot:`panel_${i}`,type,title,bindings:[],actions:[],column_span:2,row_span:1}));
  panel._draft={schema_version:1,profile_id:'demo',name:'Whole home',default_screen_id:'home',screens:[{screen_id:'home',title:'Home',composition:'freeform_grid',sections}]};
  panel._snapshot={profiles:[panel._draft],displays:[]};
  panel._selectedId='demo';panel._activeScreenId='home';panel._activeWorkspace='screens';panel._activeSectionSlot='panel_0';
  document.body.appendChild(panel);
 });
 const designer=page.locator('.grid-designer');
 await designer.waitFor();
 await page.locator(".canvas-options > summary").click();
 await page.locator('[data-preset="whole_home"]').click();
 assert.equal(await page.evaluate(()=>document.querySelector('biofects-butler-panel')._draft.screens[0].sections[0].type),'status_overview');
 await designer.screenshot({path:path.join(previewDir,'whole-home-command.png')});
 await page.locator('[data-viewport="phone"]').click();
 await page.locator('.canvas-scroll').screenshot({path:path.join(previewDir,'whole-home-phone.png')});
 await page.locator('[data-viewport="desktop"]').click();
 await designer.locator('[data-action="undo-grid"]').click();
 await page.locator('[data-preset="hero"]').click();
 assert.equal(await page.evaluate(()=>document.querySelector('biofects-butler-panel')._draft.screens[0].grid_columns),12);
 assert.equal(await page.locator('.canvas-panel').count(),6);
 await designer.screenshot({path:path.join(previewDir,'custom-canvas-desktop.png')});
 await designer.locator('[data-action="undo-grid"]').click();
 assert.equal(await page.evaluate(()=>document.querySelector('biofects-butler-panel')._draft.screens[0].grid_columns),undefined);
 await page.locator('[data-preset="hero"]').click();
 await page.locator('[data-viewport="phone"]').click();
 assert.equal(await page.locator('.canvas-resize').count(),0);
 await page.locator('.canvas-scroll').screenshot({path:path.join(previewDir,'custom-canvas-phone.png')});
 await page.locator('[data-viewport="desktop"]').click();
 const handle=page.locator('.canvas-resize').first();
 await handle.scrollIntoViewIfNeeded();
 const rect=await handle.boundingBox();
 await page.mouse.move(rect.x+14,rect.y+14);await page.mouse.down();await page.mouse.move(rect.x-80,rect.y-40,{steps:5});await page.mouse.up();
 const resized=await page.evaluate(()=>document.querySelector('biofects-butler-panel')._draft.screens[0].sections[0]);
 assert.ok(resized.column_span<8 || resized.row_span<4);
 const cell=page.locator('.canvas-cell[data-grid-column="1"][data-grid-row="7"]');
 await cell.click();
 assert.equal(await page.evaluate(()=>document.querySelector('biofects-butler-panel')._draft.screens[0].sections[0].grid_row),7);
 const dragSource = page.locator('.canvas-panel').first();
 const dragTarget = page.locator('.canvas-cell[data-grid-column="12"][data-grid-row="9"]');
 await dragSource.dragTo(dragTarget);
 assert.equal(await page.evaluate(()=>document.querySelector('biofects-butler-panel')._draft.screens[0].sections[0].grid_row),9);
 await page.locator('[data-action="auto-grid"]').click();
 assert.ok(await page.evaluate(()=>document.querySelector('biofects-butler-panel')._draft.screens[0].sections.every(s=>!s.grid_row&&!s.grid_column)));
 await page.locator('[data-field="grid_gap"]').fill('0');await page.locator('[data-field="grid_gap"]').press('Tab');
 assert.equal(await page.evaluate(()=>document.querySelector('biofects-butler-panel')._draft.screens[0].grid_gap),0);
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 assert.deepEqual(errors,[]);
 console.log('Browser smoke passed: presets, undo, desktop/phone previews, pointer resizing, cell placement, drag-and-drop, auto-arrange, zero gap, mobile overflow.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
